import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source=await fs.readFile('src/world/TerrainRoadMask.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {rasterizeRoads}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const roads=[{width:4.8,points:[{x:-30,z:0},{x:30,z:0}]},{width:4.8,points:[{x:0,z:-30},{x:0,z:30}]}];
const tint=()=>[1.08,1.02,.89],m=rasterizeRoads(roads,tint);
const pixel=(x,z)=>{const i=Math.floor((x-m.minX)/m.spanX*m.width),j=Math.floor((z-m.minZ)/m.spanZ*m.height);return [...m.data.slice((j*m.width+i)*4,(j*m.width+i+1)*4)];};
for(const [x,z] of [[0,0],[-12,0],[12,0],[0,-12],[0,12]])assert.equal(pixel(x,z)[3],255,'Junction and branches must remain fully covered');
assert.equal(pixel(8,8)[3],0,'Grass away from a road must not be painted');
assert.ok(pixel(12,2.1)[3]>0&&pixel(12,2.1)[3]<255,'Shoulders blend with soil');
assert.deepEqual(m.data,rasterizeRoads([...roads].reverse(),tint).data,'Junction must not depend on draw order');
const shifted=roads.map(r=>({...r,points:r.points.map(p=>({x:p.x+1234,z:p.z-786}))}));
const translated=rasterizeRoads(shifted,tint);
assert.ok(m.data.every((v,i)=>Math.abs(v-translated.data[i])<=1),'Road masks must keep world offsets within byte rounding');
const capped=rasterizeRoads([{width:8,points:[{x:0,z:0},{x:9000,z:8000}]}],tint,256);
assert.ok(capped.width<=256&&capped.height<=256,'Mask texture allocation must stay bounded');
assert.equal(rasterizeRoads([],tint).data[3],0,'An empty route set must remain unpainted');
console.log('Road paint: connected intersections, soft shoulders, deterministic world coordinates and bounded cache passed');
